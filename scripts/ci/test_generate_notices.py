class NoticeBundleTest(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory()
        self.fixture = Fixture(Path(self.temporary.name))

    def tearDown(self) -> None:
        self.temporary.cleanup()

    def test_renders_each_text_once_and_covers_every_crate(self) -> None:
        content = self.fixture.render()
        assert content.count("### T-") == 3
        assert "crate-a 1.0.0" in content
        assert "crate-b 2.0.0" in content
        assert content.count(WIDGET_TEXT.rstrip()) == 1
        assert content.count(MIT_TEXT.rstrip()) == 1
        assert "2 crates from 1 graphs" in content

    def test_check_passes_for_the_written_bundle(self) -> None:
        content = self.fixture.render()
        generate_notices.write(self.fixture.root, content)
        generate_notices.check(self.fixture.root, self.fixture.render())

    def test_check_fails_when_the_committed_bundle_is_stale(self) -> None:
        content = self.fixture.render()
        generate_notices.write(self.fixture.root, content)
        output = self.fixture.root / notices_sources.OUTPUT_NAME
        output.write_bytes(content.replace("crate-a 1.0.0", "crate-a 0.9.0").encode())
        assert_raises("stale", lambda: generate_notices.check(self.fixture.root, self.fixture.render()))

    def test_check_fails_when_the_committed_bundle_is_absent(self) -> None:
        assert_raises("does not exist", lambda: generate_notices.check(self.fixture.root, self.fixture.render()))

    def test_vendored_text_drift_fails(self) -> None:
        path = self.fixture.root / "scripts/ci/notices/vendored/widget/1.2.3/COPYING"
        path.write_text("tampered\n")
        assert_raises("does not match its recorded digest", lambda: notices_sources.load_manifest(self.fixture.root))

    def test_a_pin_without_vendored_text_fails(self) -> None:
        inputs = notices_sources.BuildInputs(
            pins={
                "widget": [
                    notices_sources.Pin(
                        "widget", "2.0.0", "b" * 64, "https://example.invalid/widget-2.0.0.tar.gz", "test"
                    )
                ]
            }
        )
        components = notices_sources.load_manifest(self.fixture.root)
        assert_raises("no vendored license texts", lambda: notices_sources.resolve_texts(inputs, components))

    def test_manifest_component_without_a_build_input_fails(self) -> None:
        inputs = notices_sources.BuildInputs()
        components = notices_sources.load_manifest(self.fixture.root)
        assert_raises("matches no build input", lambda: notices_sources.resolve_texts(inputs, components))

    def test_corresponding_source_pairs_the_required_version_with_its_own_url(self) -> None:
        inputs = notices_sources.BuildInputs(
            pins={
                "widget": [
                    notices_sources.Pin(
                        "widget", "1.2.3", "a" * 64, "https://example.invalid/widget-1.2.3.tar.gz", "decode"
                    ),
                    notices_sources.Pin(
                        "widget", "1.3.0", "b" * 64, "https://example.invalid/widget-1.3.0.tar.gz", "encoders"
                    ),
                ]
            },
            channels=[
                notices_sources.Channel(
                    "elixir-macos-arm64",
                    "demo-archive",
                    "upstream-tarball",
                    ("widget",),
                    "scripts/build.sh",
                    "1.0.0",
                    False,
                )
            ],
        )
        bundle = generate_notices.Bundle(inputs, {}, {}, [], [], {}, [], "", "", None)
        table = generate_notices.corresponding_source(bundle)
        assert "widget 1.3.0" in table
        assert "widget-1.3.0.tar.gz" in table
        assert "widget-1.2.3.tar.gz" not in table

    def test_renders_corresponding_source_and_written_offer(self) -> None:
        content = self.fixture.render()
        assert "## Corresponding Source" in content
        assert "vcpkg port set at baseline" in content
        assert "fix-build.patch" in content
        assert "GPL-SOURCE-OFFER.txt" in content
        assert "windows-cli" in content
        # A channel with an offer file must reference it, not duplicate it inline. ~keep
        assert "Xberg offers, valid for" not in content

    def test_check_fails_when_the_source_section_is_removed(self) -> None:
        content = self.fixture.render()
        generate_notices.write(self.fixture.root, content)
        output = self.fixture.root / notices_sources.OUTPUT_NAME
        output.write_bytes(content.replace("fix-build.patch", "").encode())
        assert_raises("stale", lambda: generate_notices.check(self.fixture.root, self.fixture.render()))

    def test_check_fails_when_the_offer_reference_is_removed(self) -> None:
        content = self.fixture.render()
        generate_notices.write(self.fixture.root, content)
        output = self.fixture.root / notices_sources.OUTPUT_NAME
        output.write_bytes(
            content.replace("| [`GPL-SOURCE-OFFER.txt`](GPL-SOURCE-OFFER.txt) | windows-cli |", "").encode()
        )
        assert_raises("stale", lambda: generate_notices.check(self.fixture.root, self.fixture.render()))

    def test_an_offer_source_shipped_under_the_staged_name_is_discovered(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            notices = root / "scripts/ci/notices"
            notices.mkdir(parents=True)
            (notices / "GPL-SOURCE-OFFER-windows-heif.txt").write_text(
                "Xberg - Written Offer of Corresponding Source\nWindows x86_64 CLI archive\n\n"
                "valid for three years. contact@xberg.io\n"
            )
            discovered = notices_sources.discover_offer_files(root)
            assert len(discovered) == 1
            path, shipped_as, channels = discovered[0]
            assert path.name == "GPL-SOURCE-OFFER-windows-heif.txt"
            assert shipped_as == "GPL-SOURCE-OFFER.txt"
            assert channels == ["windows-cli"]

    def test_an_uncovered_patched_channel_gets_an_inline_offer(self) -> None:
        manifest = self.fixture.root / "scripts/ci/notices/SOURCES.toml"
        text = manifest.read_text().replace('channels = ["windows-cli"]', "channels = []")
        manifest.write_text(text)
        assert "Xberg offers, valid for" in self.fixture.render()

    def test_a_patched_channel_without_any_offer_fails(self) -> None:
        manifest = self.fixture.root / "scripts/ci/notices/SOURCES.toml"
        text = manifest.read_text()
        manifest.write_text(text.split("[[offer]]")[0])
        self.fixture.offer.unlink()
        assert_raises("no written offer", self.fixture.render)

    def test_unknown_template_placeholder_fails(self) -> None:
        assert_raises("has no value", lambda: generate_notices.render_template("{{not_a_value}}", {"other": "x"}))


class BuildInputTest(unittest.TestCase):
    """The real repository's pins must come from its build inputs, not typed constants."""

    def setUp(self) -> None:
        self.inputs = notices_sources.build_inputs(ROOT)

    def test_libheif_versions_come_from_the_build_script_and_dockerfiles(self) -> None:
        versions = self.inputs.versions("libheif")
        assert len(versions) == 1
        assert re.fullmatch(r"\d+\.\d+\.\d+", versions[0])
        assert len({pin.sha256 for pin in self.inputs.pins["libheif"]}) == 1

    def test_libaom_tracks_both_pinned_profiles(self) -> None:
        assert len(self.inputs.versions("libaom")) >= 2

    def test_each_pinned_version_keeps_its_own_url(self) -> None:
        for version in ("3.15.2", "3.15.3"):
            pin = self.inputs.pin("libaom", version)
            assert pin.url.endswith(f"libaom-{version}.tar.gz"), pin.url
            assert pin.sha256

    def test_a_swapped_release_url_is_rejected(self) -> None:
        pins = [
            notices_sources.Pin("widget", "1.2.3", "a" * 64, "https://example.invalid/widget-1.2.3.tar.gz", "test"),
            notices_sources.Pin("widget", "1.3.0", "a" * 64, "https://example.invalid/widget-1.2.3.tar.gz", "test"),
        ]
        inputs = notices_sources.BuildInputs(pins={"widget": pins})
        assert_raises("URL naming another release", lambda: inputs.pin("widget", "1.3.0"))

    def test_a_missing_pin_version_is_rejected(self) -> None:
        inputs = notices_sources.BuildInputs(
            pins={
                "widget": [
                    notices_sources.Pin(
                        "widget", "1.2.3", "a" * 64, "https://example.invalid/widget-1.2.3.tar.gz", "test"
                    )
                ]
            }
        )
        assert_raises("no widget pin at version 1.3.0", lambda: inputs.pin("widget", "1.3.0"))

    def test_an_ambiguous_pin_version_is_rejected(self) -> None:
        inputs = notices_sources.BuildInputs(
            pins={
                "widget": [
                    notices_sources.Pin(
                        "widget", "1.3.0", "a" * 64, "https://example.invalid/widget-1.3.0.tar.gz", "one"
                    ),
                    notices_sources.Pin(
                        "widget", "1.3.0", "b" * 64, "https://other.invalid/widget-1.3.0.tar.gz", "two"
                    ),
                ]
            }
        )
        assert_raises("distinct pins", lambda: inputs.pin("widget", "1.3.0"))

    def test_every_input_has_a_vendored_manifest_row(self) -> None:
        components = notices_sources.load_manifest(ROOT)
        resolved = notices_sources.resolve_texts(self.inputs, components)
        assert "libheif" in resolved
        assert "x265" in resolved

    def test_windows_channel_discloses_the_vcpkg_patches(self) -> None:
        notices_sources.attach_channels(ROOT, self.inputs)
        windows = self.inputs.channel("windows-cli")
        assert windows.patched
        assert windows.build == "vcpkg-port"
        vcpkg = notices_sources.load_vcpkg(ROOT)
        assert vcpkg is not None
        patched = {port.name for port in vcpkg.ports if port.patches}
        assert {"libheif", "libde265", "aom"} <= patched

    def test_source_built_channels_are_marked_unmodified(self) -> None:
        notices_sources.attach_channels(ROOT, self.inputs)
        assert not self.inputs.channel("elixir-macos-arm64").patched
        assert not self.inputs.channel("php-macos-arm64").patched

    def test_the_offer_covers_the_gpl_elixir_archive(self) -> None:
        notices_sources.attach_channels(ROOT, self.inputs)
        offers = notices_sources.load_offers(ROOT)
        notices_sources.assert_offers(ROOT, self.inputs, offers)
        assert any("elixir-macos-arm64" in offer.channels for offer in offers)

    def test_fonts_are_identified_by_the_bytes_that_ship(self) -> None:
        assert {font.family for font in self.inputs.fonts} == {"DejaVu Sans", "Droid Sans Fallback", "Noto Emoji"}


class PackageNoticeGuardTest(unittest.TestCase):
    def test_a_hand_maintained_bundle_is_refused(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            (root / "LICENSE").write_text("MIT\n")
            (root / "THIRD_PARTY_LICENSES.md").write_text("# Third-Party Licenses\n\nhand written\n")
