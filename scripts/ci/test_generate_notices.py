def load_script(name: str) -> object:
    """Import a hyphenated CI script as a module."""
    spec = importlib.util.spec_from_file_location(name.replace("-", "_"), SCRIPT_DIR / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


generate_notices = load_script("generate-notices")
package_notices = load_script("package-notices")

MIT_TEXT = "MIT License\n\nPermission is hereby granted, free of charge.\n"
WIDGET_TEXT = "Widget License\n\nCopyright (c) Example.\n"


def digest(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def assert_raises(message: str, function) -> None:  # noqa: ANN001
    """Assert the call raises ValueError with a matching message."""
    error: ValueError | None = None
    try:
        function()
    except ValueError as caught:
        error = caught
    assert error is not None, f"expected ValueError matching {message!r}"
    assert re.search(message, str(error)), f"{message!r} not in {error}"


